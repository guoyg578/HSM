# 长名优先：「马鞍山」不该被「鞍山」抢先命中
_CITY_KEYS = sorted(CITIES, key=len, reverse=True)
_PROVINCE_KEYS = sorted(PROVINCES, key=len, reverse=True)


def lookup_qth(qth: str) -> tuple[float, float, str] | None:
    """QTH → (纬度, 经度, 命中的地名)。城市优先于省份，均未命中返回 None。"""
    if not qth:
        return None
    text = qth.strip().lower()
    if not text:
        return None
    for keys, table in ((_CITY_KEYS, CITIES), (_PROVINCE_KEYS, PROVINCES)):
        for name in keys:
            if name in text:
                lat, lon = table[name]
                return lat, lon, name
    return None


def qth_to_grid(qth: str) -> tuple[str, str] | None:
    """QTH → (4 位网格, 命中的地名)，无法识别返回 None。"""
    hit = lookup_qth(qth)
    if not hit:
        return None
    lat, lon, name = hit
    return latlon_to_grid(lat, lon, 4), name
